import os, shutil, subprocess, threading, re, time

def start_cloudflared(port=8501):
    """Start a Cloudflare tunnel to the given local port and print the public URL."""
    # 1) Install cloudflared if needed
    if not shutil.which("cloudflared"):
        print("Installing cloudflared...")
        subprocess.run(
            "wget -q https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-amd64.deb",
            shell=True,
            check=True,
        )
        subprocess.run(
            "dpkg -i cloudflared-linux-amd64.deb",
            shell=True,
            check=True,
        )

    # 2) Start the tunnel in a background thread and capture the URL
    def _run():
        cmd = f"cloudflared tunnel --url http://localhost:{port} --no-autoupdate"
        # merge stdout & stderr so we only read one stream
        with subprocess.Popen(
            cmd.split(),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
        ) as p:
            for line in p.stdout:
                # Look for the trycloudflare URL line
                if "trycloudflare.com" in line:
                    m = re.search(r"https://[^\s]+", line)
                    if m:
                        url = m.group(0)
                        print(f"\nStreamlit app is live at: {url}\n(Keep this Colab cell running.)")
                    else:
                        print("\nCloudflare tunnel started, check above logs for the URL.\n")
                    # we keep the process running so the tunnel stays alive
            p.wait()

    threading.Thread(target=_run, daemon=True).start()

