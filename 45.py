def monthly_pivots(df):
    m = df.resample("ME").agg({"High":"max","Low":"min","Close":"last"})
    if len(m) < 2:
        return (np.nan,)*7
    prev = m.iloc[-2]
    P = (prev.High + prev.Low + prev.Close)/3.0
    R1 = 2*P - prev.Low
    S1 = 2*P - prev.High
    R2 = P + (prev.High - prev.Low)
    S2 = P - (prev.High - prev.Low)
    R3 = prev.High + 2*(P - prev.Low)
    S3 = prev.Low - 2*(prev.High - P)
    return (P,R1,R2,R3,S1,S2,S3)



def fib_levels_236_382_500_hi(df, lookback=252):
    span = df.tail(lookback) if len(df) >= lookback else df
    hi = span["High"].max(); lo = span["Low"].min()
    if pd.isna(hi) or pd.isna(lo) or hi <= lo:
        return (np.nan, np.nan, np.nan, np.nan)
    f236 = hi - 0.236*(hi-lo)
    f382 = hi - 0.382*(hi-lo)
    f500 = hi - 0.500*(hi-lo)
    return (f236, f382, f500, hi)

def fib_levels_all(df, lookback=252):
    span = df.tail(lookback) if len(df) >= lookback else df
    hi = span["High"].max()
    lo = span["Low"].min()
    if pd.isna(hi) or pd.isna(lo) or hi <= lo:
        # 0%(Hi), 23.6, 38.2, 50, 61.8, 78.6, 100%(Lo)
        return (np.nan,)*7
    f236 = hi - 0.236*(hi-lo)
    f382 = hi - 0.382*(hi-lo)
    f500 = hi - 0.500*(hi-lo)
    f618 = hi - 0.618*(hi-lo)
    f786 = hi - 0.786*(hi-lo)
    return hi, f236, f382, f500, f618, f786, lo



def regression_stats(close, window=120, log=True):
    y = close.tail(window)
    if len(y.dropna()) < window: return (np.nan, np.nan)
    if log: y = np.log(y)
    x = np.arange(len(y))
    r = linregress(x, y)
    return (float(r.slope), float(r.rvalue**2))

def returns_over_period(close, days=63):
    if len(close.dropna()) < days+1: return np.nan
    return float((close.iloc[-1]/close.iloc[-days-1] - 1)*100.0)

def percent_above(close, ref, window=60):
    z = close.tail(window); r = ref.reindex_like(close).tail(window)
    if len(z.dropna()) < window or len(r.dropna()) < window: return np.nan
    return float((z > r).mean()*100.0)

def max_dd_from_high(close, window=120):
    y = close.tail(window)
    if len(y.dropna()) < window: return np.nan
    rm = y.cummax()
    return float((y/rm - 1).min()*100.0)  # negative %

def avg_dollar_vol(df, days=30):
    """Avg( Close * Volume ) over last N sessions."""
    if "Volume" not in df.columns: return np.nan
    c = df["Close"].tail(days); v = df["Volume"].tail(days)
    if len(c.dropna())<days or len(v.dropna())<days: return np.nan
    return float((c*v).mean())

def earnings_within_window(ticker, days=7):
    """
    Try yfinance endpoints to find the next earnings date.
    Return True if within `days` calendar days from today.
    """
    try:
        tk = yf.Ticker(ticker)
        # Preferred: get_earnings_dates
        ed = tk.get_earnings_dates(limit=1)
        if ed is not None and len(ed) > 0:
            next_dt = pd.to_datetime(ed.index[0]).to_pydatetime()
            delta = (next_dt.date() - dt.date.today()).days
            return (delta is not None) and (delta >= 0) and (delta <= days)
    except Exception:
        pass
    try:
        # Fallback: .calendar DataFrame (not always available)
        cal = yf.Ticker(ticker).calendar
        if isinstance(cal, pd.DataFrame) and "Earnings Date" in cal.index:
            raw = cal.loc["Earnings Date"].values
            # calendar sometimes returns an array of two timestamps [start, end]
            if len(raw)>0:
                nxt = pd.to_datetime(raw[0]).to_pydatetime()
                delta = (nxt.date() - dt.date.today()).days
                return (delta is not None) and (delta >= 0) and (delta <= days)
    except Exception:
        pass
    return False  # unknown = let it pass (or set True to be stricter)

