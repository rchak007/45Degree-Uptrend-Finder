def get_spx():
    """Get S&P 500 tickers from Wikipedia (robust to table/column changes)."""
    tables = _read_html_with_headers(
        "https://en.wikipedia.org/wiki/List_of_S%26P_500_companies"
    )

    for tbl in tables:
        cols = [str(c).strip() for c in tbl.columns]

        # Most common case
        if "Symbol" in cols:
            return (
                tbl["Symbol"]
                .astype(str)
                .str.strip()
                .str.replace(".", "-", regex=False)
                .tolist()
            )

        # Just in case they rename it
        if "Ticker" in cols:
            return (
                tbl["Ticker"]
                .astype(str)
                .str.strip()
                .str.replace(".", "-", regex=False)
                .tolist()
            )

    # If nothing matched, fail loudly so you see it
    raise RuntimeError("Could not find Symbol/Ticker column in SPX Wikipedia tables")




def get_ndx():
    """Get Nasdaq-100 tickers from Wikipedia (robust to 403)."""
    tables = _read_html_with_headers("https://en.wikipedia.org/wiki/Nasdaq-100")
    # Different revisions put it in different tables; find the right one
    for tbl in tables:
        if "Ticker" in tbl.columns:
            return tbl["Ticker"].str.replace(".", "-", regex=False).tolist()
        if "Symbol" in tbl.columns:  # fallback
            return tbl["Symbol"].str.replace(".", "-", regex=False).tolist()
    return []



